"""Build docs/assets/js/ears-data.js from the Humaneness Ears model card.

Usage: python3 tools/extract_ears_outputs.py docs/assets/js/ears-data.js
Downloads the model card and LAION's EmoNet/VoiceNet taxonomies, then writes every
one of the 192 scalar outputs (exact key, readable name, family, held-out Pearson r
for Base and Medium) plus the 53 vocal-burst classes. Re-run if the card changes.
"""
import json
import re
import sys
import urllib.request

CARD = "https://huggingface.co/laion/humaneness-ears-base-medium/raw/main/README.md"
EMONET = "https://raw.githubusercontent.com/LAION-AI/voicenet/main/taxonomy/emonet_taxonomy.md"
VOICENET = "https://raw.githubusercontent.com/LAION-AI/voicenet/main/taxonomy/voicenet_taxonomy.md"


def fetch(url):
    with urllib.request.urlopen(url, timeout=60) as response:
        return response.read().decode("utf-8")


def norm(text):
    return re.sub(r"[^a-z]", "", text.lower())


card, emonet, voicenet = fetch(CARD), fetch(EMONET), fetch(VOICENET)

# EmoNet: "## Group" headings followed by "| n | **Name** | ..." rows.
emo_names = {}
group = None
for line in emonet.splitlines():
    heading = re.match(r"^## (.+)$", line)
    if heading:
        group = heading.group(1).strip()
    row = re.match(r"^\| *\d+ *\| \*\*(.+?)\*\* \|", line)
    if row and group:
        emo_names[norm(row.group(1))] = (row.group(1), group)
EMO_ALIASES = {  # model keys that spell a taxonomy category differently
    "hopeenthusiasmoptimism": "hopeoptimism",
    "intoxicationalteredstatesofconsciousness": "intoxicationalteredstates",
    "jealousyandenvy": "jealousyenvy",
}

# VoiceNet: "- **[GROUP](#...)** (n dimensions)" then "  - [`CODE`](#...) Name".
vn_names = {}
group = None
for line in voicenet.splitlines():
    heading = re.match(r"^- \*\*\[(.+?)\]", line)
    if heading:
        group = heading.group(1).title().replace("&", "&")
    row = re.match(r"^  - \[`([A-Z_]+)`\]\(#[^)]*\) (.+)$", line)
    if row and group:
        vn_names[row.group(1)] = (row.group(2).strip(), group)

AUDIOBOX = {"CE": "Content enjoyment", "CU": "Content usefulness", "PC": "Production complexity", "PQ": "Production quality"}


def pretty(text):
    text = text.replace("_", " ").replace(" vs. ", " vs. ").strip()
    if text.startswith("score "):
        text = text[6:] + " score"
    return text[:1].upper() + text[1:]


def describe(key):
    if key.startswith("emo_"):
        raw = norm(key[4:])
        name, grp = emo_names[EMO_ALIASES.get(raw, raw)]
        return name, "emonet", grp
    if key.startswith("vn_"):
        name, grp = vn_names[key[3:-4]]
        return name, "voicenet", grp
    if key in ("genuineness_0_6", "blend_0_10", "R_quality"):
        return {"genuineness_0_6": "Genuineness (0–6)", "blend_0_10": "Vocal-burst blend (0–10)", "R_quality": "R_quality (legacy)"}[key], "delivery", None
    if key.startswith("eiv_extra:"):
        return pretty(key.split(":", 1)[1]), "empathic", None
    if key.startswith("audiobox:"):
        code = key.split(":", 1)[1]
        return f"{AUDIOBOX[code]} ({code})", "audiobox", None
    if key.startswith("dnsmos:"):
        code = key.split(":", 1)[1]
        return code.replace("_raw", " (raw)").replace("_", " "), "dnsmos", None
    if key == "burst_count_log1p":
        return "Vocal-burst count", "bursts", None
    if key.startswith("voiceclap_attribute:"):
        return pretty(key.split(":", 1)[1]), "voiceclap", None
    raise KeyError(key)


def number(cell):
    try:
        return round(float(cell), 4)
    except ValueError:
        return None


outputs = []
section = card.split("## All 192 scalar targets", 1)[1].split("\n## ", 1)[0]
for line in section.splitlines():
    match = re.match(r"^\| (\d+) \| `([^`]+)` \| (\d+) \| (.+) \|$", line)
    if not match:
        continue
    cells = [c.strip() for c in match.group(4).split("|")]
    name, family, grp = describe(match.group(2))
    outputs.append([int(match.group(1)), match.group(2), name, family, grp, int(match.group(3)), number(cells[2]), number(cells[6])])
assert len(outputs) == 192, len(outputs)
assert [o[0] for o in outputs] == list(range(192))

bursts_section = card.split("## Canonical 53-class vocal-burst vocabulary", 1)[1]
bursts = re.findall(r"^\| \d+ \| (.+?) \|$", bursts_section, re.M)[:53]
assert len(bursts) == 53, len(bursts)

families = {}
for o in outputs:
    families[o[3]] = families.get(o[3], 0) + 1
print(families)

with open(sys.argv[1], "w", encoding="utf-8") as fh:
    fh.write("/* Generated by tools/extract_ears_outputs.py from the Humaneness Ears model card\n"
             "   (laion/humaneness-ears-base-medium) and LAION's EmoNet/VoiceNet taxonomies.\n"
             "   outputs: [index, key, name, family, group, valid N, Base r, Medium r]; r is Pearson\n"
             "   agreement with held-out machine-annotated test targets, not human ratings. */\n")
    fh.write("window.HumanenessEars = ")
    json.dump({"outputs": outputs, "bursts": bursts}, fh, ensure_ascii=False, separators=(",", ":"))
    fh.write(";\n")
